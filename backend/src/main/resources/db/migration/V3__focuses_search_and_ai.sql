CREATE TABLE focus_items (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 course_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 content VARCHAR(2000) NOT NULL,
 original_input TEXT NULL,
 content_revision BIGINT NOT NULL DEFAULT 1,
 mastery_status VARCHAR(24) NOT NULL DEFAULT 'NOT_STARTED',
 match_status VARCHAR(24) NOT NULL DEFAULT 'NEVER',
 last_locate_job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 locate_method VARCHAR(24) NOT NULL DEFAULT 'KEYWORD',
 locate_warnings JSON NULL,
 last_scope JSON NULL,
 error_code VARCHAR(64) NULL,
 error_message VARCHAR(500) NULL,
 row_version BIGINT NOT NULL DEFAULT 1,
 deleted_at DATETIME(3) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(course_id) REFERENCES courses(id),
 CHECK(mastery_status IN ('NOT_STARTED','IN_PROGRESS','UNFAMILIAR','MASTERED')),
 CHECK(match_status IN ('NEVER','RUNNING','MATCHED','NO_MATCH','NEEDS_REVIEW','FAILED')),
 INDEX ix_focus_course(course_id,deleted_at,created_at,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE focus_slide_links (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 focus_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 slide_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 origin VARCHAR(16) NOT NULL,
 decision VARCHAR(16) NOT NULL,
 matched_focus_revision BIGINT NOT NULL,
 matched_text_revision BIGINT NULL,
 locate_job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 evidence_text VARCHAR(1000) NULL,
 reason VARCHAR(500) NULL,
 source_snapshot JSON NOT NULL,
 row_version BIGINT NOT NULL DEFAULT 1,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(focus_id) REFERENCES focus_items(id),
 FOREIGN KEY(slide_id) REFERENCES slides(id),
 UNIQUE KEY uq_focus_slide(focus_id,slide_id),
 CHECK(origin IN ('AUTO','MANUAL')),
 CHECK(decision IN ('CANDIDATE','CONFIRMED','REJECTED')),
 INDEX ix_focus_link(slide_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE ai_calls (
 id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 owner_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 course_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
 scene VARCHAR(32) NOT NULL,
 model VARCHAR(100) NOT NULL,
 prompt_version VARCHAR(32) NOT NULL,
 request_fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 quota_date DATE NOT NULL,
 status VARCHAR(24) NOT NULL,
 input_tokens BIGINT NULL,
 output_tokens BIGINT NULL,
 duration_ms BIGINT NULL,
 provider_request_id VARCHAR(255) NULL,
 error_code VARCHAR(64) NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 FOREIGN KEY(owner_id) REFERENCES app_users(id),
 FOREIGN KEY(course_id) REFERENCES courses(id),
 INDEX ix_ai_quota(owner_id,quota_date,status),
 UNIQUE KEY uq_ai_job_scene(job_id,scene)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
